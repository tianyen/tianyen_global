 buttons.forEach((b,i)=>b.addEventListener('click',()=>{slider.value=i*100;update(slider.value)}));slider.addEventListener('input',()=>update(slider.value));document.addEventListener('languagechange',()=>{current=-1;update(slider.value)});slider.max=(chapters.length-1)*100;update(0);
